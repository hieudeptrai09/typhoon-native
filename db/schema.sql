-- Schema of the typhoon database, with one example row per table.
-- The example rows form a single connected set — position 19 and the name Yagi —
-- so the file loads top to bottom with every foreign key satisfied.

CREATE SCHEMA IF NOT EXISTS catfisha_typhoons;

SET search_path TO catfisha_typhoons, public;

-- Saffir-Simpson category for typhoons ('1'-'5'), below-typhoon strength otherwise.
-- 'NT' is not a step on the scale: the JTWC never issued warnings on that storm, so it has
-- no category at all. It sorts first so the enum order still runs weakest to strongest.
CREATE TYPE storms_intensity AS ENUM ('NT', 'TD', 'TS', 'STS', '1', '2', '3', '4', '5');

-- JTWC basin letter appended to the storm number, e.g. jtwcnumber 11 + 'W' -> "11W".
CREATE TYPE suffix AS ENUM ('W', 'E', 'B', 'C');

-- Why a name left rotation.
CREATE TYPE typhoonnames_retirementreason AS ENUM ('destructive', 'language', 'misspell', 'special');

-- License lookup shared by typhoonnames.image and suggestednames.image.
CREATE TABLE imagelicenses (
    id smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name character varying NOT NULL UNIQUE,
    url character varying                    -- NULL for licenses with no canonical deed URL
);

