-- Re-runs the generators that read p_table (all of them when NULL) and applies only the
-- difference, so a fact whose text did not change keeps its row.
CREATE OR REPLACE FUNCTION catfisha_typhoons.refresh_facts(p_table text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = catfisha_typhoons, public
AS $$
DECLARE
    g record;
    texts text[];
BEGIN
    FOR g IN
        SELECT topic FROM (VALUES
            ('storms',       ARRAY['storms']),
            ('names_storms', ARRAY['typhoonnames', 'storms']),
            ('countries',    ARRAY['typhoonnames', 'positions']),
            ('names',        ARRAY['typhoonnames'])
        ) AS t(topic, tables)
        WHERE p_table IS NULL OR p_table = ANY(t.tables)
    LOOP
        EXECUTE format('SELECT ARRAY(SELECT DISTINCT f FROM catfisha_typhoons.%I() AS f)',
                       'facts_' || g.topic)
        INTO texts;

        DELETE FROM facts WHERE topic = g.topic AND text <> ALL(texts);
        INSERT INTO facts (topic, text)
        SELECT g.topic, t FROM unnest(texts) AS t
        ON CONFLICT (topic, text) DO NOTHING;
    END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION catfisha_typhoons.refresh_facts(text) FROM PUBLIC;

CREATE OR REPLACE FUNCTION catfisha_typhoons.refresh_facts_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = catfisha_typhoons, public
AS $$
BEGIN
    PERFORM catfisha_typhoons.refresh_facts(TG_TABLE_NAME);
    RETURN NULL;
END;
$$;

-- Statement-level, so a bulk edit refreshes once rather than once per row. UPDATE OF lists only
-- the columns a generator reads: editing an image, a map or a meaning leaves the facts alone.
CREATE OR REPLACE TRIGGER refresh_facts
    AFTER INSERT OR DELETE OR TRUNCATE
       OR UPDATE OF position, name, intensity, year, isstrongest, jtwcdesignation,
                    isfirst, islast, startdate, enddate
    ON catfisha_typhoons.storms
    FOR EACH STATEMENT EXECUTE FUNCTION catfisha_typhoons.refresh_facts_trigger();

CREATE OR REPLACE TRIGGER refresh_facts
    AFTER INSERT OR DELETE OR TRUNCATE
       OR UPDATE OF name, tag, position, isretired, note, language, lastyear, retirementreason
    ON catfisha_typhoons.typhoonnames
    FOR EACH STATEMENT EXECUTE FUNCTION catfisha_typhoons.refresh_facts_trigger();

CREATE OR REPLACE TRIGGER refresh_facts
    AFTER INSERT OR DELETE OR TRUNCATE OR UPDATE OF id, country
    ON catfisha_typhoons.positions
    FOR EACH STATEMENT EXECUTE FUNCTION catfisha_typhoons.refresh_facts_trigger();

