-- The fun-fact list, built inside Postgres so triggers can keep it current.
--
-- Run with `npm run facts`. The script runs this whole file in one transaction: it drops the
-- facts table, recreates it with everything that hangs off it, and fills it. Re-running it is
-- always safe and is the way to rebuild from scratch.
--
-- After that, the triggers at the bottom refresh the facts on their own whenever storms,
-- typhoonnames or positions change. A refresh only touches the facts whose text actually
-- changed, so unaffected rows keep their id.

SET search_path TO catfisha_typhoons, public;

DROP TABLE IF EXISTS catfisha_typhoons.facts;

-- topic names the generator function a fact came from (facts_<topic>), so a refresh can diff
-- one topic at a time without touching the others.
CREATE TABLE catfisha_typhoons.facts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic text NOT NULL,
    text text NOT NULL,
    generatedat timestamptz NOT NULL DEFAULT now(),
    UNIQUE (topic, text)
);

-- No policies: anon and authenticated read only through get_random_fact, which is SECURITY DEFINER.
ALTER TABLE catfisha_typhoons.facts ENABLE ROW LEVEL SECURITY;

-- The Next.js site caches the fact list under the 'facts' tag. Its trigger lives in
-- nextjs_model/typhoons/db/revalidate-webhooks.sql and disappears with the dropped table, so it
-- has to be put back here. Skipped on databases that never installed the webhooks.
DO $$
BEGIN
    IF to_regprocedure('catfisha_typhoons.revalidate_static()') IS NOT NULL THEN
        CREATE TRIGGER revalidate_facts_all
            AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON catfisha_typhoons.facts
            FOR EACH STATEMENT EXECUTE FUNCTION catfisha_typhoons.revalidate_static('facts');
    END IF;
END;
$$;

-- ============================================================================================
-- Sentence helpers
-- ============================================================================================

CREATE OR REPLACE FUNCTION catfisha_typhoons.fact_join(items text[], joiner text DEFAULT 'and')
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT CASE cardinality(items)
        WHEN 0 THEN ''
        WHEN 1 THEN items[1]
        WHEN 2 THEN items[1] || ' ' || joiner || ' ' || items[2]
        ELSE array_to_string(items[1:cardinality(items) - 1], ', ')
             || ' ' || joiner || ' ' || items[cardinality(items)]
    END;
$$;

CREATE OR REPLACE FUNCTION catfisha_typhoons.fact_plural(n bigint, one text, many text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT CASE WHEN n = 1 THEN one ELSE many END;
$$;

-- Builds "<clause>, which is/are <names>." so a count and its name list stay one fact.
CREATE OR REPLACE FUNCTION catfisha_typhoons.fact_with_names(clause text, items text[])
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT clause || ', '
        || catfisha_typhoons.fact_plural(cardinality(items), 'which is', 'which are') || ' '
        || catfisha_typhoons.fact_join(items) || '.';
$$;

-- ============================================================================================
-- Generators
-- ============================================================================================
-- One function per set of source tables. refresh_facts maps each one to the tables it reads,
-- so keep that list in sync when a generator starts reading another table.

CREATE OR REPLACE FUNCTION catfisha_typhoons.facts_storms()
RETURNS SETOF text
LANGUAGE plpgsql
STABLE
SET search_path = catfisha_typhoons, public
AS $$
DECLARE
    items text[];
    n int;
    m int;
    r record;
    last_complete_year int := EXTRACT(YEAR FROM current_date)::int - 1;
BEGIN
    -- --- Cross-basin facts ---

    -- Position is the naming agency, not the birthplace: a few Hawaiian names (Li 1994, Nolo) went
    -- to storms that formed east of 140°W, so the E in their designation is what marks all 3
    -- basins. That condition is repeated below as
    -- (position = 142 OR (position = 141 AND jtwcdesignation LIKE '%E')).

    items := ARRAY(SELECT DISTINCT name::text AS name FROM storms WHERE position = 141 ORDER BY name);
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format(
            'There are %s names given in Hawaiian by CPHC that crossed into the West Pacific basin',
            n), items);
    END IF;

    items := ARRAY(SELECT DISTINCT name::text AS name FROM storms WHERE position = 142 ORDER BY name);
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format(
            'There are %s names assigned by NHC that cross 3 Pacific basins', n), items);
    END IF;

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE position = 141 AND jtwcdesignation LIKE '%E'
        ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' '
            || fact_plural(n, 'is the only name given in Hawaiian by CPHC',
                              'are the only names given in Hawaiian by CPHC')
            || ' to cross all 3 Pacific basins.';
    END IF;

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE (position = 142 OR (position = 141 AND jtwcdesignation LIKE '%E'))
        ORDER BY year, startdate
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format('There %s %s storm%s that crossed all 3 Pacific basins',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's')), items);
    END IF;

    items := ARRAY(
        SELECT name::text FROM storms
        WHERE (position = 142 OR (position = 141 AND jtwcdesignation LIKE '%E'))
        GROUP BY name HAVING COUNT(*) >= 2 ORDER BY name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' '
            || fact_plural(n, 'is the only name that was given', 'are the only names that were given')
            || ' to 2 storms crossing 3 Pacific basins.';
    END IF;

    -- --- Category 5 from external basins ---

    items := ARRAY(
        SELECT DISTINCT name::text AS name FROM storms
        WHERE position = 142 AND intensity = '5' ORDER BY name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' '
            || fact_plural(n, 'is the only storm from NHC to reach category 5',
                              'are the storms from NHC that reached category 5') || '.';
    END IF;

    items := ARRAY(
        SELECT DISTINCT name::text AS name FROM storms
        WHERE position = 141 AND intensity = '5' ORDER BY name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' '
            || fact_plural(n, 'is the storm named in Hawaiian to reach category 5',
                              'are the storms named in Hawaiian that reached category 5') || '.';
    END IF;

    -- --- Indian Ocean to Pacific ---

    items := ARRAY(SELECT DISTINCT name::text AS name FROM storms WHERE position = 143 ORDER BY name);
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' ' || fact_plural(n, 'is the only storm', 'are the only storms')
            || ' that crossed from the Indian Ocean to the Pacific Ocean.';
    END IF;

    -- --- Strongest storms records ---

    items := ARRAY(
        SELECT name::text FROM storms WHERE isstrongest AND year >= 2000
        GROUP BY name HAVING COUNT(*) > 1 ORDER BY name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' ' || fact_plural(n, 'is the only name', 'are the only names')
            || ' with more than one record-strength storm.';
    END IF;

    -- --- Strongest storms not Cat 5 ---

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE isstrongest AND intensity <> '5' AND year >= 2000 ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('Since 2000, %s %s that did not reach category 5.', fact_join(items),
            fact_plural(n, 'is the only record-strength storm', 'are the only record-strength storms'));
    END IF;

    -- --- First storms that are Cat 5 ---

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE isfirst AND intensity = '5' ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('Since 2000, %s %s to reach category 5.', fact_join(items),
            fact_plural(n, 'is the only season-opening storm', 'are the only season-opening storms'));
    END IF;

    -- --- Season openers / closers that were also the strongest of their season ---

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE isfirst AND isstrongest ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('Since 2000, %s %s.', fact_join(items),
            fact_plural(n, 'is the only storm to open its season and also be its strongest',
                           'are the only storms to open their season and also be its strongest'));
    END IF;

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE islast AND isstrongest ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('Since 2000, %s %s.', fact_join(items),
            fact_plural(n, 'is the only storm to close its season and also be its strongest',
                           'are the only storms to close their season and also be its strongest'));
    END IF;

    -- --- Storms spanning multiple years ---

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE EXTRACT(YEAR FROM enddate) > EXTRACT(YEAR FROM startdate) AND year >= 2000
        ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('Since 2000, %s %s that span multiple years.', fact_join(items),
            fact_plural(n, 'is the only storm', 'are the only storms'));
    END IF;

    -- --- Longest-lived storm ---

    SELECT MAX(enddate - startdate + 1) INTO m
    FROM storms WHERE position <= 140 AND enddate IS NOT NULL;
    IF m IS NOT NULL THEN
        items := ARRAY(
            SELECT format('%s (%s)', name, year) FROM storms
            WHERE position <= 140 AND enddate - startdate + 1 = m ORDER BY year, name
        );
        RETURN NEXT format('Since 2000, %s %s %s days.', fact_join(items),
            fact_plural(cardinality(items), 'is the longest-lived storm, lasting',
                                            'are the longest-lived storms, each lasting'), m);
    END IF;

    -- --- Seasons ending with Cat 5 ---

    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms
        WHERE islast AND intensity = '5' ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format(
            'Since 2000, there %s %s season%s that ended with a category 5 storm, which ended with %s.',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's'), fact_join(items));
    END IF;

    -- --- Off-season and late-season months ---

    FOREACH m IN ARRAY ARRAY[1, 2, 3, 4, 12] LOOP
        items := ARRAY(
            SELECT format('%s (%s)', name, year) FROM storms
            WHERE isstrongest AND EXTRACT(MONTH FROM startdate) = m AND year >= 2000
            ORDER BY year, name
        );
        n := cardinality(items);
        IF n > 0 THEN
            RETURN NEXT format('Since 2000, %s %s to form in %s.', fact_join(items),
                fact_plural(n, 'is the only record-strength storm', 'are the only record-strength storms'),
                to_char(make_date(2000, m, 1), 'FMMonth'));
        END IF;
    END LOOP;

    FOREACH m IN ARRAY ARRAY[6, 7, 8] LOOP
        items := ARRAY(
            SELECT format('%s (%s)', name, year) FROM storms
            WHERE isfirst AND EXTRACT(MONTH FROM startdate) = m
            ORDER BY year, name
        );
        n := cardinality(items);
        IF n > 0 THEN
            RETURN NEXT format('Since 2000, %s %s to form in %s.', fact_join(items),
                fact_plural(n, 'is the only season-opening storm', 'are the only season-opening storms'),
                to_char(make_date(2000, m, 1), 'FMMonth'));
        END IF;
    END LOOP;

    FOREACH m IN ARRAY ARRAY[1, 2, 3, 4, 12] LOOP
        items := ARRAY(
            SELECT format('%s (%s)', name, year) FROM storms
            WHERE intensity = '5' AND EXTRACT(MONTH FROM startdate) = m AND year >= 2000
            ORDER BY year, name
        );
        n := cardinality(items);
        IF n > 0 THEN
            RETURN NEXT fact_with_names(format(
                'Since 2000, there %s only %s category 5 storm%s that formed in %s',
                fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's'),
                to_char(make_date(2000, m, 1), 'FMMonth')), items);
        END IF;
    END LOOP;

    -- --- Names where EVERY appearance hit a given intensity (times >= 2) ---

    -- The category 3+ pass also picks up the all-5 and all-4 names, which is intentional.
    FOR r IN
        SELECT u.label, g.total, array_agg(g.name ORDER BY g.name) AS names
        FROM (VALUES
            (1, ARRAY['5']::storms_intensity[], 'a category 5 storm'),
            (2, ARRAY['4']::storms_intensity[], 'a category 4 storm'),
            (3, ARRAY['3', '4', '5']::storms_intensity[], 'a category 3 or stronger storm')
        ) AS u(ord, levels, label)
        CROSS JOIN LATERAL (
            SELECT s.name::text AS name, COUNT(*) AS total
            FROM storms s WHERE s.position <= 140 AND s.year >= 2000
            GROUP BY s.name, s.position
            HAVING COUNT(*) >= 2 AND COUNT(*) = COUNT(*) FILTER (WHERE s.intensity = ANY(u.levels))
        ) AS g
        GROUP BY u.ord, u.label, g.total
        ORDER BY u.ord, g.total
    LOOP
        RETURN NEXT format('%s %s that appeared %s times, each time as %s.', fact_join(r.names),
            fact_plural(cardinality(r.names), 'is the only storm', 'are the only storms'),
            r.total, r.label);
    END LOOP;

    -- --- Year records ---

    SELECT year, COUNT(*) AS cnt INTO r FROM storms WHERE year >= 2000
    GROUP BY year ORDER BY cnt DESC, year LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('Since 2000, %s had the most storms of any season, with %s.', r.year, r.cnt);
    END IF;

    -- Only seasons up to last year count, since the current one is still filling up. A new
    -- season's first storm is an insert into storms, which re-runs this on its own.
    SELECT MIN(cnt) INTO n FROM (
        SELECT COUNT(*) AS cnt FROM storms
        WHERE year >= 2000 AND year <= last_complete_year GROUP BY year
    ) AS sub;
    items := ARRAY(
        SELECT year::text FROM storms WHERE year >= 2000 AND year <= last_complete_year
        GROUP BY year HAVING COUNT(*) = n ORDER BY year
    );
    IF cardinality(items) > 0 THEN
        RETURN NEXT format('Between 2000 and %s, %s with the fewest storms (%s) %s %s.',
            last_complete_year, fact_plural(cardinality(items), 'the year', 'the years'), n,
            fact_plural(cardinality(items), 'is', 'are'), fact_join(items));
    END IF;

    SELECT year INTO r FROM storms WHERE intensity = '5' AND year >= 2000
    GROUP BY year ORDER BY COUNT(*) DESC, year LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('Since 2000, %s had the most category 5 storms of any season.', r.year);
    END IF;

    -- --- JTWC tracking oddities ---

    -- Every storm the JTWC never issued live warnings on (Haiyan included, even though it was
    -- later numbered — see the absurdity fact below).
    items := ARRAY(
        SELECT format('%s (%s)', name, year) FROM storms WHERE intensity = 'MD' ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format('There %s %s storm%s the JTWC never issued warnings on',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's')), items);
    END IF;

    -- The absurdity: not tracked, yet somehow still numbered in post-season reanalysis (Haiyan 27W).
    items := ARRAY(
        SELECT format('%s (%s, %s)', name, year, jtwcdesignation) FROM storms
        WHERE intensity = 'MD' AND jtwcdesignation IS NOT NULL ORDER BY year, name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' ' || fact_plural(n, 'is the only storm', 'are the only storms')
            || ' the JTWC never tracked, yet somehow still carries a JTWC number — assigned in post-season reanalysis.';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION catfisha_typhoons.facts_names_storms()
RETURNS SETOF text
LANGUAGE plpgsql
STABLE
SET search_path = catfisha_typhoons, public
AS $$
DECLARE
    items text[];
    n int;
    r record;
BEGIN
    -- --- Weak storms retired for destructive reason ---

    FOR r IN
        SELECT DISTINCT t.name::text AS name, s.intensity
        FROM typhoonnames t
        INNER JOIN storms s ON t.name = s.name AND t.position = s.position AND s.year = t.lastyear
        WHERE t.isretired AND t.retirementreason = 'destructive' AND t.position <= 140
          AND s.year >= 2000 AND s.intensity IN ('TD', 'TS', 'STS')
        ORDER BY name
    LOOP
        RETURN NEXT format('Although %s was only %s, it was retired due to the destruction it caused.',
            r.name,
            CASE r.intensity
                WHEN 'TD' THEN 'a tropical depression'
                WHEN 'STS' THEN 'a severe tropical storm'
                ELSE 'a tropical storm'
            END);
    END LOOP;

    -- --- Names never reaching typhoon intensity ---

    items := ARRAY(
        SELECT t.name::text FROM typhoonnames t
        WHERE t.position <= 140 AND NOT t.isretired
          AND NOT EXISTS (
              SELECT 1 FROM storms s WHERE s.name = t.name AND s.position = t.position
                AND s.year >= 2000 AND s.intensity IN ('1', '2', '3', '4', '5')
          )
          AND EXISTS (
              SELECT 1 FROM storms s WHERE s.name = t.name AND s.position = t.position
                AND s.year >= 2000
          )
        ORDER BY t.name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format('There %s %s storm name%s that never reached typhoon intensity',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's')), items);
    END IF;

    -- --- Max used non-retired names ---

    SELECT MAX(cnt) INTO n FROM (
        SELECT COUNT(s.id) AS cnt FROM typhoonnames t
        INNER JOIN storms s ON t.name = s.name AND t.position = s.position
        WHERE NOT t.isretired AND t.position <= 140 AND s.year >= 2000
        GROUP BY t.name, t.position
    ) AS sub;
    IF n > 0 THEN
        items := ARRAY(
            SELECT t.name::text FROM typhoonnames t
            INNER JOIN storms s ON t.name = s.name AND t.position = s.position
            WHERE NOT t.isretired AND t.position <= 140 AND s.year >= 2000
            GROUP BY t.name, t.position HAVING COUNT(s.id) = n
            ORDER BY t.name
        );
        RETURN NEXT fact_with_names(format('%s name%s been used %s times since 2000 without being retired',
            cardinality(items), fact_plural(cardinality(items), ' has', 's have'), n), items);
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION catfisha_typhoons.facts_countries()
RETURNS SETOF text
LANGUAGE plpgsql
STABLE
SET search_path = catfisha_typhoons, public
AS $$
DECLARE
    items text[];
    n int;
    r record;
BEGIN
    -- --- Total names and countries in WPAC ---

    SELECT COUNT(*) AS total, COUNT(DISTINCT p.country) AS countries INTO r
    FROM typhoonnames t INNER JOIN positions p ON t.position = p.id
    WHERE t.position <= 140;
    RETURN NEXT format(
        'There are %s storm names contributed by %s countries in the western Pacific basin since 2000.',
        r.total, r.countries);

    -- --- Country contributions ---

    SELECT p.country, COUNT(*) AS cnt INTO r
    FROM typhoonnames t INNER JOIN positions p ON t.position = p.id
    WHERE t.position <= 140 GROUP BY p.country ORDER BY cnt DESC, p.country LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('%s has contributed the most names (%s).', r.country, r.cnt);
    END IF;

    SELECT MIN(cnt) INTO n FROM (
        SELECT COUNT(*) AS cnt FROM typhoonnames t INNER JOIN positions p ON t.position = p.id
        WHERE t.position <= 140 GROUP BY p.country
    ) AS sub;
    items := ARRAY(
        SELECT p.country::text FROM typhoonnames t INNER JOIN positions p ON t.position = p.id
        WHERE t.position <= 140 GROUP BY p.country HAVING COUNT(*) = n ORDER BY p.country
    );
    IF cardinality(items) > 0 THEN
        RETURN NEXT format('%s contributed the fewest names (%s).', fact_join(items), n);
    END IF;

    -- --- Category breakdown per country ---

    FOR r IN
        SELECT country, array_agg(format('%s (%s)', tag, cnt) ORDER BY cnt DESC, tag) AS parts
        FROM (
            SELECT p.country::text AS country, t.tag, COUNT(*) AS cnt
            FROM typhoonnames t INNER JOIN positions p ON t.position = p.id
            WHERE t.position <= 140 GROUP BY p.country, t.tag
        ) AS sub
        GROUP BY country ORDER BY country
    LOOP
        RETURN NEXT format('%s has contributed names in the %s %s.', r.country,
            fact_plural(cardinality(r.parts), 'category', 'categories'), fact_join(r.parts));
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION catfisha_typhoons.facts_names()
RETURNS SETOF text
LANGUAGE plpgsql
STABLE
SET search_path = catfisha_typhoons, public
AS $$
DECLARE
    items text[];
    n int;
    r record;
BEGIN
    -- --- Tag records ---

    SELECT tag, COUNT(*) AS cnt INTO r FROM typhoonnames WHERE position <= 140
    GROUP BY tag ORDER BY cnt DESC, tag LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('%s is the category with the most names (%s).', r.tag, r.cnt);
    END IF;

    SELECT tag, COUNT(*) AS cnt INTO r FROM typhoonnames WHERE position <= 140
    GROUP BY tag ORDER BY cnt, tag LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('%s is the category with the fewest names (%s).', r.tag, r.cnt);
    END IF;

    -- --- Rare languages ---

    FOR r IN
        SELECT language, array_agg(name::text ORDER BY name) AS names
        FROM typhoonnames WHERE position <= 140
        GROUP BY language HAVING COUNT(*) <= 3 ORDER BY COUNT(*), language
    LOOP
        n := cardinality(r.names);
        RETURN NEXT fact_with_names(format('There %s only %s name%s from the %s language',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's'), r.language), r.names);
    END LOOP;

    -- --- Names per tag ---

    FOR r IN
        SELECT tag, COUNT(*) AS cnt, array_agg(name::text ORDER BY name) AS names
        FROM typhoonnames WHERE position <= 140
        GROUP BY tag ORDER BY cnt, tag
    LOOP
        IF r.cnt > 3 THEN
            RETURN NEXT format('There are %s names in the category %s.', r.cnt, r.tag);
        ELSE
            RETURN NEXT fact_with_names(format('There %s only %s name%s in the category %s',
                fact_plural(r.cnt, 'is', 'are'), r.cnt, fact_plural(r.cnt, '', 's'), r.tag), r.names);
        END IF;
    END LOOP;

    -- --- Category breakdown per language ---

    FOR r IN
        SELECT language, array_agg(format('%s (%s)', tag, cnt) ORDER BY cnt DESC, tag) AS parts
        FROM (
            SELECT language::text AS language, tag, COUNT(*) AS cnt
            FROM typhoonnames WHERE position <= 140 GROUP BY language, tag
        ) AS sub
        GROUP BY language ORDER BY language
    LOOP
        RETURN NEXT format('The %s language has names in the %s %s.', r.language,
            fact_plural(cardinality(r.parts), 'category', 'categories'), fact_join(r.parts));
    END LOOP;

    -- --- Language reason retirements ---

    items := ARRAY(
        SELECT name::text FROM typhoonnames
        WHERE retirementreason = 'language' AND isretired ORDER BY name
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_with_names(format('There %s %s name%s retired for language-related reasons',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's')), items);
    END IF;

    -- --- Nearest equator ---

    items := ARRAY(SELECT name::text FROM typhoonnames WHERE retirementreason = 'special' ORDER BY name);
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT fact_join(items) || ' ' || fact_plural(n, 'is the storm', 'are the storms')
            || ' that formed closest to the equator on record.';
    END IF;

    -- --- Retirement reasons with notes ---

    FOR r IN
        SELECT name, note FROM typhoonnames
        WHERE retirementreason = 'language' AND isretired AND note IS NOT NULL
        ORDER BY name
    LOOP
        IF r.note ~ '^(has |was |is )' THEN
            RETURN NEXT format('The name %s was retired because it %s.', r.name, r.note);
        ELSIF r.note ~ '^resubmitted ' THEN
            RETURN NEXT format('The name %s was retired because it was %s.', r.name, r.note);
        ELSE
            RETURN NEXT format('The name %s was retired due to its meaning: %s.', r.name, r.note);
        END IF;
    END LOOP;

    -- --- Missing letters ---

    items := ARRAY(
        SELECT l FROM unnest(regexp_split_to_array('ABCDEFGHIJKLMNOPQRSTUVWXYZ', '')) AS l
        WHERE NOT EXISTS (
            SELECT 1 FROM typhoonnames WHERE position <= 140 AND left(upper(name), 1) = l
        )
        ORDER BY l
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('No names start with the %s %s.',
            fact_plural(n, 'letter', 'letters'), fact_join(items, 'or'));
    END IF;

    items := ARRAY(
        SELECT l FROM unnest(regexp_split_to_array('ABCDEFGHIJKLMNOPQRSTUVWXYZ', '')) AS l
        WHERE NOT EXISTS (
            SELECT 1 FROM typhoonnames WHERE position <= 140 AND strpos(upper(name), l) > 0
        )
        ORDER BY l
    );
    n := cardinality(items);
    IF n > 0 THEN
        RETURN NEXT format('No western Pacific names contain the %s %s at all.',
            fact_plural(n, 'letter', 'letters'), fact_join(items, 'or'));
    END IF;

    -- --- Letters with only active or only retired names ---

    FOR r IN
        SELECT only_retired, array_agg(letter ORDER BY letter COLLATE "C") AS letters
        FROM (
            SELECT UPPER(LEFT(name, 1)) AS letter, bool_and(isretired) AS only_retired
            FROM typhoonnames WHERE position <= 140
            GROUP BY letter
            HAVING bool_and(isretired) OR NOT bool_or(isretired)
        ) AS sub
        GROUP BY only_retired ORDER BY only_retired
    LOOP
        n := cardinality(r.letters);
        RETURN NEXT format('The %s %s %s only %s.',
            fact_plural(n, 'letter', 'letters'), fact_join(r.letters), fact_plural(n, 'has', 'have'),
            CASE WHEN r.only_retired THEN 'retired names (no active names)'
                 ELSE 'active names (no retired names)' END);
    END LOOP;

    -- --- Rare starting letters ---

    FOR r IN
        SELECT UPPER(LEFT(name, 1)) AS letter, array_agg(name::text ORDER BY name) AS names
        FROM typhoonnames WHERE position <= 140
        GROUP BY letter HAVING COUNT(*) <= 3 ORDER BY COUNT(*), letter
    LOOP
        n := cardinality(r.names);
        RETURN NEXT fact_with_names(format('There %s only %s name%s starting with the letter %s',
            fact_plural(n, 'is', 'are'), n, fact_plural(n, '', 's'), r.letter), r.names);
    END LOOP;

    -- --- Most/least common starting letter ---

    SELECT UPPER(LEFT(name, 1)) AS letter, COUNT(*) AS cnt INTO r
    FROM typhoonnames WHERE position <= 140 GROUP BY letter ORDER BY cnt DESC, letter LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('The letter %s has the most names starting with it (%s).', r.letter, r.cnt);
    END IF;

    SELECT UPPER(LEFT(name, 1)) AS letter, COUNT(*) AS cnt INTO r
    FROM typhoonnames WHERE position <= 140 GROUP BY letter ORDER BY cnt, letter LIMIT 1;
    IF FOUND THEN
        RETURN NEXT format('The letter %s has the fewest names starting with it (%s).', r.letter, r.cnt);
    END IF;
END;
$$;

